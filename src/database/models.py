# ---------------------------------------------------------------------------
# Index definitions
# ---------------------------------------------------------------------------

RAW_INDEXES = [
    # Unique constraint: don't store the same URL twice
    {"keys": [("url", 1)], "options": {"unique": True, "name": "url_unique"}},
    # Quickly filter by quality rank during cleaning
    {"keys": [("rank", 1)], "options": {"name": "rank_idx"}},
    # Support feed-level queries
    {"keys": [("feed", 1)], "options": {"name": "feed_idx"}},
    # Sort / filter by publication date
    {"keys": [("pub", -1)], "options": {"name": "pub_date_idx"}},
]

CLEAN_INDEXES = [
    {"keys": [("url", 1)], "options": {"unique": True, "name": "url_unique"}},
    # Category / subcategory will be added once the classifier is integrated
    {"keys": [("feed", 1)], "options": {"name": "feed_idx"}},
    {"keys": [("pub", -1)], "options": {"name": "pub_date_idx"}},
    {"keys": [("lang", 1)], "options": {"name": "lang_idx"}},
]


def build_article_dict(
    *,
    url: str,
    title: str,
    feed: str,
    body: str,
    type_: str | None = None,
    pub: str | None = None,
    ret: str | None = None,
    lang: str | None = None,
    refs: list[str] | None = None,
    sum_: str | None = None,
    text: str | None = None,
    clean_text: str | None = None,
    money_tags: list[str] | None = None,
    percent_tags: list[str] | None = None,
    datetime_tags: list[str] | None = None,
    url_tags: list[dict[str, str]] | None = None,
    doc_stats: dict[str, int] | None = None,
    cleaning_flags: dict[str, bool] | None = None,
    signal_counts: dict[str, int] | None = None,
    rank_reasons: list[str] | None = None,
    source_author: str | None = None,
    source_tags: list[str] | None = None,
    source_summary: str | None = None,
    source_published: str | None = None,
    quarantined_at: str | None = None,
    rank: int | None = None,
) -> dict[str, Any]:
    """Return a plain dict that matches the article schema."""
    return {
        "url":   url,
        "title": title,
        "feed":  feed,
        "type":  type_,
        "pub":   pub,
        "ret":   ret,
        "lang":  lang,
        "refs":  refs,
        "sum":   sum_,
        "body":  body,
        "text":  text,
        "clean_text": clean_text,
        "money_tags": money_tags,
        "percent_tags": percent_tags,
        "datetime_tags": datetime_tags,
        "url_tags": url_tags,
        "doc_stats": doc_stats,
        "cleaning_flags": cleaning_flags,
        "signal_counts": signal_counts,
        "rank_reasons": rank_reasons,
        "source_author": source_author,
        "source_tags": source_tags,
        "source_summary": source_summary,
        "source_published": source_published,
        "quarantined_at": quarantined_at,
        "rank":  rank,
    }

"""
Article data model and MongoDB collection schema.

Each article document maps to exactly one MongoDB document.
The schema is enforced via a JSON Schema validator at the collection level
so that MongoDB itself rejects documents that are structurally incorrect.

Field reference
---------------
_id   : ObjectId (auto-generated by MongoDB)
url   : str   — canonical URL of the article (unique index)
title : str   — headline / title
feed  : str   — publisher / RSS feed name (e.g. "BBC News")
type  : str   — content type (e.g. "news", "opinion", "analysis")
pub   : str   — publication date (ISO-8601 string, e.g. "2026-03-11T09:00:00Z")
ret   : str   — retrieval/scrape datetime (ISO-8601)
lang  : str   — BCP-47 language tag (e.g. "en", "es")
refs  : list  — list of URLs referenced/cited within the article
sum   : str   — short summary / lede paragraph
body  : str   — main article body (no boilerplate/nav)
text  : str   — full raw text of the page (body + any ancillary text)

Cleaning rank (only present in the raw collection)
----------------------------------------------------
rank  : int
  0 — complete document, all fields present
  1 — non-crucial fields missing (dates, summary, refs, …); may be fixable via URL
  2 — crucial fields missing; document should be discarded
"""

